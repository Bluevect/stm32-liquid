/**
 * @brief 获取字符点阵。
 * @param[in] character 字符。
 * @return 点阵数据。
 */
static const uint8_t *OLED_GetGlyph(char character) {
  if ((character >= '0') && (character <= '9')) {
    return FONT_DIGITS[character - '0'];
  }
  if ((character >= 'A') && (character <= 'Z')) {
    return FONT_UPPER[character - 'A'];
  }
  if ((character >= 'a') && (character <= 'z')) {
    return FONT_LOWER[character - 'a'];
  }

  for (uint32_t i = 0U; i < (sizeof(FONT_PUNCTUATION) / sizeof(FONT_PUNCTUATION[0])); ++i) {
    if (FONT_PUNCTUATION[i].code == (uint8_t)character) {
      return FONT_PUNCTUATION[i].rows;
    }
  }

  return FONT_PUNCTUATION[21].rows;
}

/**
 * @brief 写入 OLED 命令。
 * @param[in,out] display OLED 实例。
 * @param[in] commands 命令数组。
 * @param[in] count 命令数量。
 * @return 成功返回 true，否则返回 false。
 */
static bool OLED_WriteCommands(BSP_OLED_t *display, const uint8_t *commands, uint16_t count) {
  uint8_t packet[32];

  if (display == NULL || commands == NULL) {
    return false;
  }

  packet[0] = OLED_CONTROL_COMMAND;
  memcpy(&packet[1], commands, count);
  return I2C_Hardware_Write(&display->i2c, packet, (uint16_t)(count + 1U), OLED_I2C_TIMEOUT) == HAL_OK;
}

/**
 * @brief 写入单条 OLED 命令。
 * @param[in,out] display OLED 实例。
 * @param[in] command 命令。
 * @return 成功返回 true，否则返回 false。
 */
static bool OLED_WriteCommand(BSP_OLED_t *display, uint8_t command) {
  return OLED_WriteCommands(display, &command, 1U);
}

/**
 * @brief 设置全屏地址窗口。
 * @param[in,out] display OLED 实例。
 * @return 成功返回 true，否则返回 false。
 */
static bool OLED_SetAddressWindow(BSP_OLED_t *display) {
  static const uint8_t window[] = {
      0x21U, 0x00U, (uint8_t)(BSP_OLED_WIDTH - 1U), 0x22U, 0x00U, (uint8_t)(BSP_OLED_PAGES - 1U),
  };

  return OLED_WriteCommands(display, window, sizeof(window));
}

/**
 * @brief 检查 OLED 是否响应。
 * @param[in,out] display OLED 实例。
 * @return 响应返回 true，否则返回 false。
 */
bool BSP_OLED_IsReady(BSP_OLED_t *display) {
  return (display != NULL) && (I2C_Hardware_IsReady(&display->i2c, 3U, OLED_I2C_TIMEOUT) == HAL_OK);
}

/**
 * @brief 初始化 OLED。
 * @param[out] display OLED 实例。
 * @param[in] i2cBus 所属 I2C 总线。
 * @return 成功返回 true，否则返回 false。
 */
bool BSP_OLED_Init(BSP_OLED_t *display, I2C_Bus_t *i2cBus) {
  static const uint8_t initCommands[] = {
      0xAEU, 0xD5U, 0x80U, 0xA8U, 0x3FU, 0xD3U, 0x00U, 0x40U, 0xA1U, 0xC8U, 0xDAU, 0x12U, 0x81U,
      0xCFU, 0xD9U, 0xF1U, 0xDBU, 0x30U, 0x20U, 0x00U, 0xA4U, 0xA6U, 0x2EU, 0x8DU, 0x14U,
  };
  if ((display == NULL) || (i2cBus == NULL)) {
    return false;
  }

  if (I2C_Hardware_Attach(&display->i2c, i2cBus, BSP_OLED_DEFAULT_ADDRESS) != HAL_OK) {
    return false;
  }

  /* CubeMX 默认 100 kHz；切到快速模式可把整帧刷新从约 92 ms 降到约 23 ms。 */
  (void)I2C_Bus_SetSpeed(i2cBus, BSP_OLED_I2C_SPEED_HZ);

  if (I2C_Hardware_IsReady(&display->i2c, 3U, OLED_I2C_TIMEOUT) != HAL_OK) {
    return false;
  }

  HAL_Delay(100U);
  if (!OLED_WriteCommands(display, initCommands, sizeof(initCommands))) {
    return false;
  }

  BSP_OLED_Clear(display);
  if (!BSP_OLED_Display(display) || !BSP_OLED_SetDisplayEnabled(display, true)) {
    return false;
  }

  HAL_Delay(100U);
  return true;
}

void BSP_OLED_Clear(BSP_OLED_t *display) { BSP_OLED_Fill(display, 0x00U); }

void BSP_OLED_Fill(BSP_OLED_t *display, uint8_t pattern) {
  if (display != NULL) {
    memset(display->buffer, pattern, sizeof(display->buffer));
  }
}

void BSP_OLED_DrawPixel(BSP_OLED_t *display, int32_t x, int32_t y, bool on) {
  if ((display == NULL) || (x < 0) || (x >= (int32_t)BSP_OLED_WIDTH) || (y < 0) ||
      (y >= (int32_t)BSP_OLED_HEIGHT)) {
    return;
  }

  uint16_t index = (uint16_t)(((uint16_t)y / 8U) * BSP_OLED_WIDTH + (uint16_t)x);
  uint8_t mask = (uint8_t)(1U << ((uint8_t)y & 0x07U));

  if (on) {
    display->buffer[index] |= mask;
  } else {
    display->buffer[index] &= (uint8_t)~mask;
  }
}

void BSP_OLED_DrawLine(BSP_OLED_t *display, int32_t x0, int32_t y0, int32_t x1, int32_t y1, bool on) {
  int32_t dx = (x1 >= x0) ? (x1 - x0) : (x0 - x1);
  int32_t sx = (x0 < x1) ? 1 : -1;
  int32_t dy = (y1 >= y0) ? (y0 - y1) : (y1 - y0);
  int32_t sy = (y0 < y1) ? 1 : -1;
  int32_t error = dx + dy;

  for (;;) {
    int32_t twiceError = 2 * error;

    BSP_OLED_DrawPixel(display, x0, y0, on);
    if ((x0 == x1) && (y0 == y1)) {
      break;
    }
    if (twiceError >= dy) {
      error += dy;
      x0 += sx;
    }
    if (twiceError <= dx) {
      error += dx;
      y0 += sy;
    }
  }
}

void BSP_OLED_DrawRect(BSP_OLED_t *display, int32_t x, int32_t y, int32_t width, int32_t height, bool filled, bool on) {
  if ((width <= 0) || (height <= 0)) {
    return;
  }

  if (filled) {
    for (int32_t row = 0; row < height; ++row) {
      BSP_OLED_DrawLine(display, x, y + row, x + width - 1, y + row, on);
    }
    return;
  }

  BSP_OLED_DrawLine(display, x, y, x + width - 1, y, on);
  BSP_OLED_DrawLine(display, x, y + height - 1, x + width - 1, y + height - 1, on);
  BSP_OLED_DrawLine(display, x, y, x, y + height - 1, on);
  BSP_OLED_DrawLine(display, x + width - 1, y, x + width - 1, y + height - 1, on);
}

void BSP_OLED_DrawBitmap(BSP_OLED_t *display, int32_t x, int32_t y, const uint8_t *bitmap, int32_t width,
                         int32_t height, bool on) {
  if ((display == NULL) || (bitmap == NULL)) {
    return;
  }

  for (int32_t row = 0; row < height; ++row) {
    for (int32_t column = 0; column < width; ++column) {
      uint32_t byteIndex = (uint32_t)(row * ((width + 7) / 8) + column / 8);
      uint8_t bitMask = (uint8_t)(1U << (column & 0x07U));

      if ((bitmap[byteIndex] & bitMask) != 0U) {
        BSP_OLED_DrawPixel(display, x + column, y + row, on);
      }
    }
  }
}

void BSP_OLED_DrawChar(BSP_OLED_t *display, uint8_t x, uint8_t page, char character) {
  if ((display == NULL) || (page >= BSP_OLED_PAGES) || (x >= BSP_OLED_WIDTH)) {
    return;
  }

  const uint8_t *glyph = OLED_GetGlyph(character);

  for (uint8_t column = 0U; column < (OLED_CHAR_WIDTH - 1U); ++column) {
    uint8_t value = 0U;
    uint8_t columnMask = (uint8_t)(0x10U >> column);

    for (uint8_t row = 0U; row < 7U; ++row) {
      if ((glyph[row] & columnMask) != 0U) {
        value |= (uint8_t)(1U << row);
      }
    }

    if ((uint8_t)(x + column) < BSP_OLED_WIDTH) {
      display->buffer[(uint16_t)page * BSP_OLED_WIDTH + x + column] = value;
    }
  }

  if ((uint8_t)(x + OLED_CHAR_WIDTH - 1U) < BSP_OLED_WIDTH) {
    display->buffer[(uint16_t)page * BSP_OLED_WIDTH + x + OLED_CHAR_WIDTH - 1U] = 0x00U;
  }
}

void BSP_OLED_PrintString(BSP_OLED_t *display, uint8_t x, uint8_t page, const char *text) {
  uint8_t cursorX = x;
  uint8_t cursorPage = page;

  if ((display == NULL) || (text == NULL)) {
    return;
  }

  while (*text != '\0') {
    if (*text == '\r') {
      ++text;
      continue;
    }
    if (*text == '\n') {
      cursorX = 0U;
      ++cursorPage;
      ++text;
      continue;
    }
    if ((uint16_t)cursorX + OLED_CHAR_WIDTH > BSP_OLED_WIDTH) {
      cursorX = 0U;
      ++cursorPage;
    }
    if (cursorPage >= BSP_OLED_PAGES) {
      return;
    }

    BSP_OLED_DrawChar(display, cursorX, cursorPage, *text);
    cursorX = (uint8_t)(cursorX + OLED_CHAR_WIDTH);
    ++text;
  }
}

int BSP_OLED_Printf(BSP_OLED_t *display, uint8_t x, uint8_t page, const char *format, ...) {
  char text[64];
  va_list arguments;

  if ((display == NULL) || (format == NULL)) {
    return -1;
  }

  va_start(arguments, format);
  int length = vsnprintf(text, sizeof(text), format, arguments);
  va_end(arguments);

  if (length >= 0) {
    BSP_OLED_PrintString(display, x, page, text);
  }
  return length;
}

bool BSP_OLED_Display(BSP_OLED_t *display) {
  uint8_t packet[BSP_OLED_WIDTH + 1U];

  if ((display == NULL) || !OLED_SetAddressWindow(display)) {
    return false;
  }

  packet[0] = OLED_CONTROL_DATA;
  for (uint16_t page = 0U; page < BSP_OLED_PAGES; ++page) {
    memcpy(&packet[1], &display->buffer[page * BSP_OLED_WIDTH], BSP_OLED_WIDTH);
    if (I2C_Hardware_Write(&display->i2c, packet, sizeof(packet), OLED_I2C_TIMEOUT) != HAL_OK) {
      return false;
    }
  }

  return true;
}

bool BSP_OLED_SetContrast(BSP_OLED_t *display, uint8_t contrast) {
  uint8_t commands[] = {0x81U, contrast};

  return OLED_WriteCommands(display, commands, sizeof(commands));
}

bool BSP_OLED_SetDisplayEnabled(BSP_OLED_t *display, bool enabled) {
  return OLED_WriteCommand(display, enabled ? 0xAFU : 0xAEU);
}

bool BSP_OLED_SetInverted(BSP_OLED_t *display, bool inverted) {
  return OLED_WriteCommand(display, inverted ? 0xA7U : 0xA6U);
}
